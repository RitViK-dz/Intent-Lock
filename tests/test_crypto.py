"""Security and functional tests for Ed25519 cryptographic operations."""

import pytest
from pathlib import Path
from cryptography.hazmat.primitives.asymmetric import ed25519

from app.crypto import (
    load_or_create_keypair,
    sign,
    verify,
    public_key_to_pem,
)


def test_load_or_create_keypair_generates_and_persists(tmp_path: Path):
    """Verify keypair is generated and saved when keys directory is empty."""
    keys_dir = tmp_path / "keys"
    priv_key, pub_key = load_or_create_keypair(keys_dir)

    assert isinstance(priv_key, ed25519.Ed25519PrivateKey)
    assert isinstance(pub_key, ed25519.Ed25519PublicKey)

    priv_file = keys_dir / "issuer_private.pem"
    pub_file = keys_dir / "issuer_public.pem"
    assert priv_file.exists()
    assert pub_file.exists()

    # Loading again from the same directory must return identical keys
    priv_key2, pub_key2 = load_or_create_keypair(keys_dir)
    assert priv_key.private_bytes_raw() == priv_key2.private_bytes_raw()
    assert pub_key.public_bytes_raw() == pub_key2.public_bytes_raw()


def test_sign_and_verify_roundtrip(tmp_path: Path):
    """Verify that a signature generated by private key verifies successfully with public key."""
    priv_key, pub_key = load_or_create_keypair(tmp_path)
    data = b"IntentLock: human approved action"

    signature = sign(priv_key, data)
    assert len(signature) == 64  # Ed25519 signatures are exactly 64 bytes

    # Signature must verify successfully
    assert verify(pub_key, signature, data) is True


def test_tampering_data_fails_verification(tmp_path: Path):
    """Verify that changing even one byte of the payload fails verification."""
    priv_key, pub_key = load_or_create_keypair(tmp_path)
    data = b'{"item":"laptop-14in","payee":"STORE-ACCT-001"}'

    signature = sign(priv_key, data)

    # Attacker tampers with payee account
    tampered_data = b'{"item":"laptop-14in","payee":"ATTACK-ACCT-666"}'
    assert verify(pub_key, signature, tampered_data) is False


def test_tampering_signature_fails_verification(tmp_path: Path):
    """Verify that modifying the signature bytes fails verification."""
    priv_key, pub_key = load_or_create_keypair(tmp_path)
    data = b"Important action bytes"

    signature = bytearray(sign(priv_key, data))
    # Flip one byte in signature
    signature[0] ^= 0xFF

    assert verify(pub_key, bytes(signature), data) is False


def test_different_keypair_fails_verification(tmp_path: Path):
    """Verify that a signature made by keypair A fails verification under keypair B."""
    priv_key_a, _ = load_or_create_keypair(tmp_path / "keys_a")
    _, pub_key_b = load_or_create_keypair(tmp_path / "keys_b")

    data = b"Data signed by authority A"
    sig_a = sign(priv_key_a, data)

    # Verifying authority A's signature with authority B's public key must fail
    assert verify(pub_key_b, sig_a, data) is False


def test_verify_never_raises_on_invalid_input(tmp_path: Path):
    """Verify that verify() returns False on malformed signatures or unexpected bytes, never raising."""
    _, pub_key = load_or_create_keypair(tmp_path)

    # Empty signature
    assert verify(pub_key, b"", b"data") is False
    # Truncated signature
    assert verify(pub_key, b"short_sig", b"data") is False
    # Random garbage
    assert verify(pub_key, b"\x00" * 64, b"data") is False


def test_public_key_to_pem_format(tmp_path: Path):
    """Verify public_key_to_pem returns standard PEM-encoded SubjectPublicKeyInfo string."""
    _, pub_key = load_or_create_keypair(tmp_path)
    pem_str = public_key_to_pem(pub_key)

    assert isinstance(pem_str, str)
    assert "-----BEGIN PUBLIC KEY-----" in pem_str
    assert "-----END PUBLIC KEY-----" in pem_str
